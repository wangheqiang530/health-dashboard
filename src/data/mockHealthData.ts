function generateHrTimeline(hasMorningWorkout: boolean = true): { time: string; hr: number; isWorkout?: boolean }[] {
  const points: { time: string; hr: number; isWorkout?: boolean }[] = [];
  const hours = [
    '00:00', '01:00', '02:00', '03:00', '04:00', '05:00', '06:00', '07:00',
    '08:00', '09:00', '10:00', '11:00', '12:00', '13:00', '14:00', '15:00',
    '16:00', '17:00', '18:00', '19:00', '20:00', '21:00', '22:00', '23:00'
  ];

  hours.forEach((time, index) => {
    let hr = 68;
    let isWorkout = false;

    if (index >= 0 && index <= 6) {
      hr = 52 + Math.floor(Math.sin(index) * 6) + (index % 2 === 0 ? 3 : 0);
    } else if (index === 7) {
      hr = 72;
    } else if (index === 10 && hasMorningWorkout) {
      hr = 158;
      isWorkout = true;
    } else if (index === 11 && hasMorningWorkout) {
      hr = 95;
    } else if (index >= 12 && index <= 14) {
      hr = 71 + (index % 3);
    } else if (index >= 15 && index <= 18) {
      hr = 78 + (index % 4);
    } else if (index >= 19 && index <= 21) {
      hr = 74 - (index - 19) * 2;
    } else {
      hr = 64;
    }

    points.push({ time, hr, isWorkout });
  });

  return points;
}

